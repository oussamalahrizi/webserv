import os
import http.cookies
import sys

# Set the content type for the response
print("Content-Type: text/html\r")
print("\r")  # Blank line indicating end of headers

# Create a Cookie object
cookies = http.cookies.SimpleCookie(os.environ.get("HTTP_COOKIE", ""))

# HTML header
print("<html>")
print("<head><title>Cookie Test</title></head>")
print("<body>")
print("<h1>Testing Cookies</h1>")

# Check if there are any cookies
if cookies:
    print("<h2>Cookies received:</h2>")
    print("<ul>")
    for key, morsel in cookies.items():
        print(f"<li>{key}: {morsel.value}</li>")
    print("</ul>")
else:
	print(f"cookies error : {cookies}", file=sys.stderr)
	print("<h2>No cookies received.</h2>")

